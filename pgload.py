#!/usr/bin/env python3
"""Export loesje.db (SQLite) to a Postgres SQL file: schema + full data reload.

    python3 pgload.py                          # writes loesje.sql
    freepod shell psql < loesje.sql            # load into the deployment's database
    psql "$DATABASE_URL" < loesje.sql          # or any other Postgres

The data is replaced in one transaction, so the site never sees a half-loaded
database. Run it again after re-scraping or re-OCR'ing.
"""

import argparse
import re
import sqlite3
from pathlib import Path

from textutil import decide_word_count, fold

ROOT = Path(__file__).resolve().parent


def copy_value(v):
    """Encode one value for COPY ... FROM STDIN (text format)."""
    if v is None:
        return r"\N"
    s = str(v)
    return (s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r"))


def copy_block(out, table, cols, rows):
    out.write(f"COPY {table} ({', '.join(cols)}) FROM stdin;\n")
    for r in rows:
        out.write("\t".join(copy_value(v) for v in r) + "\n")
    out.write("\\.\n\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", default=ROOT / "loesje.db")
    ap.add_argument("--out", default=ROOT / "loesje.sql")
    args = ap.parse_args()

    from review import connect as connect_with_overrides  # merges word_overrides.csv
    src = connect_with_overrides() if Path(args.db) == ROOT / "loesje.db" else sqlite3.connect(args.db)
    overrides = dict(src.execute("SELECT poster_id, word_count FROM word_overrides"))
    posters = []
    for (pid, slug, title, text, pub_date, wp_date, filename, w, h, alt) in src.execute(
        """SELECT id, slug, title, text, pub_date, wp_date, filename, image_width, image_height, alt_text
           FROM posters ORDER BY id"""
    ):
        # One CMS title contains literal <br> tags as line breaks; use the usual " / ".
        title = re.sub(r"\s*<br\s*/?>\s*", " / ", title or "", flags=re.I) or None
        has_text = bool(text and text.strip())
        if pid in overrides:  # read by hand where title and OCR disagreed
            wc, wc_src = overrides[pid], "manual"
        else:
            wc, wc_src = decide_word_count(text, title)
        posters.append((
            pid, slug, title, text if has_text else None, pub_date, pub_date or (wp_date or "")[:10] or None,
            filename, w, h, alt, wc, wc_src,
            fold(" ".join(filter(None, (title, text, alt)))),
        ))
    terms = src.execute("SELECT id, taxonomy, slug, name FROM terms ORDER BY id").fetchall()
    links = src.execute("SELECT poster_id, term_id FROM poster_terms ORDER BY 1, 2").fetchall()

    with open(args.out, "w", encoding="utf-8") as out:
        out.write("-- Generated by pgload.py from loesje.db; do not edit.\n")
        out.write("\\set ON_ERROR_STOP on\n\n")
        out.write((ROOT / "schema.sql").read_text(encoding="utf-8") + "\n")
        out.write("BEGIN;\n")
        out.write("TRUNCATE poster_terms, terms, posters;\n\n")
        copy_block(out, "posters", [
            "id", "slug", "title", "text", "pub_date", "sort_date", "filename", "image_width",
            "image_height", "alt_text", "word_count", "word_count_source", "search_text",
        ], posters)
        copy_block(out, "terms", ["id", "taxonomy", "slug", "name"], terms)
        copy_block(out, "poster_terms", ["poster_id", "term_id"], links)
        out.write("COMMIT;\nANALYZE posters;\nANALYZE terms;\nANALYZE poster_terms;\n")

    by_src = {k: sum(1 for p in posters if p[11] == k) for k in ("title", "text", "manual")}
    print(f"wrote {args.out}: {len(posters)} posters (word counts by source: {by_src}), "
          f"{len(terms)} terms, {len(links)} links")


if __name__ == "__main__":
    main()
